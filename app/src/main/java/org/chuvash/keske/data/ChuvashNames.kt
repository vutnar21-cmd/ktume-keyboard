package org.chuvash.keske.data

/**
 * МОДУЛЬ: ChuvashNames.kt — базовый список имён для экспериментальной фичи
 * «автозаглавные имена собственные».
 *
 * Идея: при завершении слова пробелом клавиатура проверяет его по списку и,
 * если это имя, набранное со строчной буквы, заменяет первую букву на заглавную.
 *
 * Список намеренно короткий (базовый). Пополняется без изменения кода.
 */
object ChuvashNames {

    private val names: Set<String> = setOf(
        // мужские
        "айдар", "азамат", "альберт", "анатолий", "андрей", "алексей", "аркадий",
        "артём", "борис", "валерий", "василий", "виктор", "виталий", "владимир",
        "вячеслав", "геннадий", "георгий", "григорий", "данил", "дмитрий", "евгений",
        "егор", "иван", "игнат", "игорь", "илья", "кирилл", "константин", "кузьма",
        "лаврентий", "леонид", "максим", "михаил", "мирон", "никита", "никифор",
        "николай", "олег", "павел", "пётр", "прохор", "роман", "савва", "сергей",
        "степан", "тимофей", "тихон", "фёдор", "фома", "эмиль", "эдуард", "юлиан",
        "юрий", "яков",
        // женские
        "агафья", "аграфена", "акулина", "алина", "анастасия", "анна", "антонина",
        "валентина", "вера", "галина", "дарья", "евдокия", "екатерина", "елена",
        "зинаида", "зоя", "ирина", "клавдия", "кристина", "ксения",
        "лидия", "любовь", "мария", "матрёна", "надежда", "наталья", "оксана",
        "ольга", "пелагея", "полина", "прасковья", "раиса", "светлана", "софья",
        "таисия", "татьяна", "ульяна", "феодора", "эльвира", "юлия"
    )

    /** true, если слово есть в списке имён (без учёта регистра). */
    fun isName(word: String): Boolean = word.lowercase() in names

    /**
     * Возвращает слово с заглавной первой буквой, если это имя, набранное со строчной.
     * Иначе null — вызывающая сторона ничего не меняет.
     */
    fun capitalizeIfName(word: String): String? {
        if (word.isEmpty()) return null
        if (word.first().isUpperCase()) return null
        if (!isName(word)) return null
        return word.replaceFirstChar { it.uppercaseChar() }
    }
}
